"""Open the supplied human audit tool: corners, masks, then validation. [AI-CODE]

No coordinates or foreground labels are generated by this helper. The student
must click and draw each annotation in the supplied GUI before accepting it.
"""
import csv
import json
from pathlib import Path
import subprocess
import sys

CODE = Path(__file__).resolve().parents[1]
PLAN = CODE / "student_files/personal_preparation/poster_01/audit_plan.json"


def annotated_frames(filename, clip_id, annotator):
    path = CODE / "manifests" / filename
    if not path.exists():
        return set()
    with path.open(encoding="utf-8", newline="") as stream:
        return {int(row["frame"]) for row in csv.DictReader(stream)
                if row["clip_id"] == clip_id and row["annotator"] == annotator}


def invoke(*args):
    return subprocess.run([sys.executable, "-m", "overlaylab.annotate", *args], cwd=CODE).returncode


def main():
    plan = json.loads(PLAN.read_text(encoding="utf-8"))
    clip_id, annotator = plan["clip_id"], plan["annotator"]
    corner_ids, mask_ids = plan["corner_frames"], plan["mask_frames"]
    print("Annotator:", annotator, flush=True)
    print("Corners: TL -> TR -> BR -> BL, Enter to save each frame.", flush=True)
    print("Masks: click polygon, Enter to fill, s to save; empty-mask frames: s.", flush=True)
    print("Estimate an occluded corner manually from the visible poster edges; never label a folder corner.", flush=True)
    print("q stops the current stage; this helper will not proceed if frames are incomplete.", flush=True)
    missing = sorted(set(corner_ids) - annotated_frames("audit_corners.csv", clip_id, annotator))
    if missing:
        if invoke("corners", clip_id, "--frames", *map(str, missing), "--annotator", annotator):
            raise SystemExit("Corner tool failed; inspect the console output.")
    if not set(corner_ids) <= annotated_frames("audit_corners.csv", clip_id, annotator):
        raise SystemExit("Corners incomplete. Run this helper again to continue missing frames.")
    missing = sorted(set(mask_ids) - annotated_frames("audit_masks.csv", clip_id, annotator))
    if missing:
        if invoke("masks", clip_id, "--frames", *map(str, missing), "--annotator", annotator,
                  "--occluder", plan["occluder"]):
            raise SystemExit("Mask tool failed; inspect the console output.")
    if not set(mask_ids) <= annotated_frames("audit_masks.csv", clip_id, annotator):
        raise SystemExit("Masks incomplete. Run this helper again to continue missing frames.")
    raise SystemExit(invoke("check", clip_id))


if __name__ == "__main__":
    main()
